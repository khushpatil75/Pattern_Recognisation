    "import numpy as np\n",
    "import os\n",
    "from tensorflow.keras.datasets import mnist\n",
    "from tensorflow.keras.utils import to_categorical\n",
    "\n",
    "# EMNIST\n",
    "try:\n",
    "    from emnist import extract_training_samples, extract_test_samples\n",
    "except:\n",
    "    raise ImportError(\"Install EMNIST: pip install emnist\")\n",
    "\n",
    "# -------------------------\n",
    "# 1. Process MNIST\n",
    "# -------------------------\n",
    "def process_mnist():\n",
    "    print(\"Downloading and processing MNIST...\")\n",
    "    (x_train, y_train), (x_test, y_test) = mnist.load_data()\n",
    "    x_train = x_train.astype('float32') / 255.0\n",
    "    x_test = x_test.astype('float32') / 255.0\n",
    "    x_train = np.expand_dims(x_train, -1)\n",
    "    x_test = np.expand_dims(x_test, -1)\n",
    "    y_train = to_categorical(y_train)\n",
    "    y_test = to_categorical(y_test)\n",
    "    np.savez_compressed(\"datasets/mnist.npz\", x_train=x_train, y_train=y_train,\n",
    "                        x_test=x_test, y_test=y_test)\n",
    "    print(\"MNIST saved to datasets/mnist.npz\")\n",
    "\n",
    "# -------------------------\n",
    "# 2. Process EMNIST Letters\n",
    "# -------------------------\n",
    "def process_emnist():\n",
    "    print(\"Downloading and processing EMNIST Letters...\")\n",
    "    x_train, y_train = extract_training_samples('letters')\n",
    "    x_test, y_test = extract_test_samples('letters')\n",
    "\n",
    "    # normalize and reshape\n",
    "    x_train = x_train.astype('float32') / 255.0\n",
    "    x_test = x_test.astype('float32') / 255.0\n",
    "    x_train = np.expand_dims(x_train, -1)\n",
    "    x_test = np.expand_dims(x_test, -1)\n",
    "\n",
    "    # adjust labels (EMNIST letters start at 1)\n",
    "    y_train -= 1\n",
    "    y_test -= 1\n",
    "    y_train = to_categorical(y_train)\n",
    "    y_test = to_categorical(y_test)\n",
    "\n",
    "    np.savez_compressed(\"datasets/emnist_letters.npz\", x_train=x_train, y_train=y_train,\n",
    "                        x_test=x_test, y_test=y_test)\n",
    "    print(\"EMNIST Letters saved to datasets/emnist_letters.npz\")\n",
    "\n",
    "# -------------------------\n",
    "# 3. Process Devanagari dataset\n",
    "# -------------------------\n",
    "def process_devanagari(devanagari_folder=\"datasets/devanagari\"):\n",
    "    print(\"Processing Devanagari dataset...\")\n",
    "    \n",
    "    x_train_list, y_train_list = [], []\n",
    "    x_test_list, y_test_list = [], []\n",
    "\n",
    "    # folders should be: datasets/devanagari/train/{class_name}/*.png\n",
    "    #                    datasets/devanagari/test/{class_name}/*.png\n",
    "    from PIL import Image\n",
    "\n",
    "    # Process train\n",
    "    train_folder = os.path.join(devanagari_folder, \"train\")\n",
    "    classes = sorted(os.listdir(train_folder))\n",
    "    class_map = {cls_name: idx for idx, cls_name in enumerate(classes)}\n",
    "\n",
    "    for cls_name in classes:\n",
    "        cls_path = os.path.join(train_folder, cls_name)\n",
    "        for img_name in os.listdir(cls_path):\n",
    "            img_path = os.path.join(cls_path, img_name)\n",
    "            img = Image.open(img_path).convert('L').resize((32, 32))\n",
    "            x_train_list.append(np.array(img))\n",
    "            y_train_list.append(class_map[cls_name])\n",
    "\n",
    "    # Process test\n",
    "    test_folder = os.path.join(devanagari_folder, \"test\")\n",
    "    classes_test = sorted(os.listdir(test_folder))\n",
    "    for cls_name in classes_test:\n",
    "        cls_path = os.path.join(test_folder, cls_name)\n",
    "        for img_name in os.listdir(cls_path):\n",
    "            img_path = os.path.join(cls_path, img_name)\n",
    "            img = Image.open(img_path).convert('L').resize((32, 32))\n",
    "            x_test_list.append(np.array(img))\n",
    "            y_test_list.append(class_map[cls_name])\n",
    "\n",
    "    x_train = np.expand_dims(np.array(x_train_list, dtype='float32') / 255.0, -1)\n",
    "    x_test = np.expand_dims(np.array(x_test_list, dtype='float32') / 255.0, -1)\n",
    "    y_train = to_categorical(np.array(y_train_list))\n",
    "    y_test = to_categorical(np.array(y_test_list))\n",
    "\n",
    "    np.savez_compressed(\"datasets/devanagari.npz\", x_train=x_train, y_train=y_train,\n",
    "                        x_test=x_test, y_test=y_test)\n",
    "    print(\"Devanagari dataset saved to datasets/devanagari.npz\")\n",
    "\n",
    "# -------------------------\n",
    "# MAIN\n",
    "# -------------------------\n",
    "if __name__ == \"__main__\":\n",
    "    os.makedirs(\"datasets\", exist_ok=True)\n",
    "    process_mnist()\n",
    "    process_emnist()\n",
    "    process_devanagari(devanagari_folder=\"datasets/devanagari\")\n",
    "    print(\"All datasets processed and saved!\")\n"
